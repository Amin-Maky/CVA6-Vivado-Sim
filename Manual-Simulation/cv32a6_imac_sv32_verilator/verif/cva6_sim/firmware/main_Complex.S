.section .data
.align 6
.global tohost
tohost: .dword 0

.global fromhost
fromhost: .dword 0

.align 4
array_src:
    .word 0x11111111, 0x22222222, 0x33333333, 0x44444444
    .word 0x55555555, 0x66666666, 0x77777777, 0x88888888
array_dst:
    .space 32

.section .text
.global _start
_start:
    # -----------------------------------------------------
    # ۱. تست ALU و Data Hazards (وابستگی‌های پشت سر هم)
    # -----------------------------------------------------
    li x1, 0x12345678
    li x2, 0x87654321
    add x3, x1, x2     # باید بشه 0x99999999
    sub x4, x1, x2     # تست تفریق
    xor x5, x3, x4     # Data Hazard: وابستگی مستقیم به x3 و x4
    srai x6, x5, 4     # تست شیفت محاسباتی
    slli x7, x6, 2     # تست شیفت منطقی

    # -----------------------------------------------------
    # ۲. تست M-Extension (ضرب) و Branch Prediction
    # محاسبه فاکتوریل عدد ۷
    # -----------------------------------------------------
    li t0, 7           # کانتر
    li t1, 1           # نتیجه
fact_loop:
    mul t1, t1, t0     # ضرب پیاپی
    addi t0, t0, -1
    bnez t0, fact_loop # پرش به عقب (چالش برای Branch Predictor)

    # -----------------------------------------------------
    # ۳. تست Memory Access (Load/Store) و پوینترها
    # کپی کردن آرایه و تغییر مقادیر حین کپی
    # -----------------------------------------------------
    la s0, array_src
    la s1, array_dst
    li s2, 8           # تعداد عناصر
copy_loop:
    lw a0, 0(s0)       # خواندن از حافظه
    addi a0, a0, 0x10  # تغییر دیتا (برای اینکه فقط کپی ساده نباشه)
    sw a0, 0(s1)       # نوشتن در حافظه
    addi s0, s0, 4     # آپدیت پوینتر مبدا
    addi s1, s1, 4     # آپدیت پوینتر مقصد
    addi s2, s2, -1    # کاهش کانتر
    bgtz s2, copy_loop

    # -----------------------------------------------------
    # ۴. تست Control Flow (فراخوانی تابع با JAL و برگشت با JALR)
    # -----------------------------------------------------
    jal ra, bitwise_test

    # -----------------------------------------------------
    # ۵. پایان موفقیت‌آمیز و توقف شبیه‌سازی
    # -----------------------------------------------------
    # تریگر کردن مانیتور تست‌بنچ شما
    li t0, 0x80001000
    li t1, 0xDEADBEEF
    sw t1, 0(t0)

    # سیگنال توقف به Spike
    la t0, tohost
    li t1, 1           # 1 = PASS
    sw t1, 0(t0)

end_loop:
    j end_loop         # چرخه بی‌نهایت پایانی

# -----------------------------------------------------
# ساب‌روتین تستی
# -----------------------------------------------------
bitwise_test:
    li t2, 0xAAAA
    li t3, 0x5555
    and t4, t2, t3     # باید بشه 0
    or  t4, t2, t3     # باید بشه 0xFFFF
    ret                # معادل jalr x0, 0(ra)

